const {chromium}=require('playwright'),assert=require('node:assert/strict');
const {fixture,modules}=require('./admin.cjs');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']}),context=await browser.newContext();
 const data=structuredClone(fixture);
 Object.assign(data.products[0],{fabric:'Test cotton',fit:'Regular test fit',careInstructions:'Test care instructions',lowStockThreshold:20});
 Object.assign(data.orders[0],{trackingNumber:'TRACK123',courierService:'Test courier',trackingUrl:'https://courier.example/track'});
 data.orders[0].customer.uid='admin1';
 let action;
 await context.route('**/*',route=>{
  const u=new URL(route.request().url()),m=u.pathname.match(/firebase_(app|auth|firestore)\.js$/);
  if(m)return route.fulfill({contentType:'application/javascript',body:modules[m[1]].replace(JSON.stringify(fixture),JSON.stringify(data))});
  if(u.pathname==='/catalogue.json')return route.fulfill({contentType:'application/json',body:JSON.stringify(data.products)});
  if(u.pathname==='/api/admin/security/authenticator/status')return route.fulfill({json:{available:true,verified:true,enrolled:true,expiresAt:Date.now()+900000}});
  if(u.pathname==='/api/admin/order-action'){action=route.request().postDataJSON();return route.fulfill({json:{success:true,notificationQueued:true}})}
  if(u.pathname==='/api/delivery')return route.fulfill({json:{markets:data.settings.find(x=>x.id==='markets').markets}});
  if(u.pathname.startsWith('/api/'))return route.fulfill({json:{rate:1}});
  if(u.pathname.endsWith('.png'))return route.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="600" height="600"/>'});
  if(u.hostname==='127.0.0.1')return route.continue();
  return route.fulfill({body:''});
 });
 const page=await context.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5173/za/t/tee/tee');
 await page.getByText('Fabric & composition',{exact:true}).click();
 await page.getByText('Test cotton',{exact:true}).waitFor();
 await page.getByText('Estimated delivery:',{exact:false}).waitFor();
 assert.match(await page.locator('.dx-delivery-info').innerText(),/70/);
 for(const width of [390,1280]){await page.setViewportSize({width,height:900});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)}
 await page.goto('http://127.0.0.1:5173/za/admin/products/tee');
 await page.getByLabel('Fabric & composition',{exact:true}).fill('Verified fabric');
 await page.getByLabel('Low-stock alert threshold',{exact:true}).fill('3');
 await page.getByRole('button',{name:'Save product',exact:true}).click();
 await page.waitForFunction(()=>window.__adminWrites.some(x=>x.ref.name==='products'));
 const saved=await page.evaluate(()=>window.__adminWrites.find(x=>x.ref.name==='products').payload);
 assert.equal(saved.fabric,'Verified fabric');assert.equal(saved.lowStockThreshold,3);
 await page.goto('http://127.0.0.1:5173/za/admin/inventory');
 await page.getByLabel('Show only low or empty stock').check();
 await page.locator('th').filter({hasText:'Alert threshold'}).waitFor();
 assert.equal(await page.locator('tbody tr').count(),2);
 await page.goto('http://127.0.0.1:5173/za/admin/orders/order1');
 await page.getByLabel('Tracking number',{exact:true}).fill('TRACK456');
 await page.getByRole('button',{name:'Save tracking',exact:true}).click();
 await page.getByText('Tracking saved. Customer notification queued.',{exact:true}).waitFor();
 assert.equal(action.action,'tracking');assert.equal(action.trackingNumber,'TRACK456');
 await page.goto('http://127.0.0.1:5173/za/member/orders/order1');
 await page.getByText('Tracking number: TRACK123',{exact:false}).waitFor();
 assert.equal(await page.getByRole('link',{name:'Track parcel'}).getAttribute('href'),'https://courier.example/track');
 assert.deepEqual(errors,[]);
 await browser.close();
 console.log('Shopping details: product save, responsive delivery, variant alerts and paid-order tracking passed.');
})().catch(e=>{console.error(e);process.exit(1)});
